#include<stdio.h>
/////////////////////////////////////////////////////////////////////////////////
//      
//          Funtion  Name : Accept 
//          Input :         Integer
//          Output :        Integer
//          Description :   print N * 
//          Date :          19/10/2026
//          Author :        Sarthak Babalu Gurav 
//
/////////////////////////////////////////////////////////////////////////////////
void Accept(int iNo)
{
    int iCnt = 0;
    iCnt=iNo;

    if(iCnt < 0)     //updater
    {
        iCnt = -iCnt;
    }
    
    while(iCnt>=0)
    {
       printf("*");
       iCnt--;
    }
}
/////////////////////////////////////////////////////////////////////////////////
//
//          Entry Point Of the application
//
/////////////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue = 0;
    

    printf("Enter a number \n");
    scanf("%d",&iValue);

    Accept(iValue);

    return 0;
}

