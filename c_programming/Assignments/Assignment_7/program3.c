#include<stdio.h>
#include<stdlib.h>
/////////////////////////////////////////////////////////////////////////////////
//
//          Function Name : Pattern        
//          Input         : Integer 
//          Output        : Integer
//          Description   : Print a pattern of $ and *
//          Date          : 2/11/2026
//          Author        : Sarthak Babalu Gurav    
//////////////////////////////////////////////////////////////////////////////////
void Pattern(int iNo)
{
    int iCnt = 0;

    for(iCnt=-iNo;iCnt<=iNo;iCnt++)     
    {
        printf("%d\t",iCnt);
    }
    printf("\n");
}
/////////////////////////////////////////////////////////////////////////////////
//
//          Entry Point Of the application
//
/////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    printf("Enter the Value  : \n");
    scanf("%d",&iValue);

    Pattern(iValue);

    return EXIT_SUCCESS;
}
