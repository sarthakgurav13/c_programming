#include<stdio.h>
/////////////////////////////////////////////////////////////////////////////////
//      
//          Funtion  Name : Accept 
//          Input :         Integer
//          Output :        Integer
//          Description :   print N * 
//          Date :          19/10/2026
//          Author :        Sarthak Babalu Gurav 
//
/////////////////////////////////////////////////////////////////////////////////
void Accept(int iNo)
{
    int iCnt = 0;

    for(iCnt=1;iCnt<=iNo;iCnt++)
    {
        printf("*");

    }

}
/////////////////////////////////////////////////////////////////////////////////
//
//          Entry Point Of the application
//
/////////////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue = 0;
    

    printf("Enter a number \n");
    scanf("%d",&iValue);

    Accept(iValue);

    return 0;
}

